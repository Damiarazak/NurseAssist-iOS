# ── CELL 7 ───────────────────────────────────────────────────────────────
cells.append(c(
    "# CELL 7 - Helper Functions: Segment, Crop, Copy-Paste Augment\n"
    "\n"
    "def segment_wound(image_path, prompt='wound'):\n"
    "    \"\"\"Return (binary_mask, bbox_xyxy) or (None, None) if no wound found.\"\"\"\n"
    "    img_arr = np.array(Image.open(image_path).convert('RGB'))\n"
    "    H, W = img_arr.shape[:2]\n"
    "\n"
    "    if USE_MEDSAM3:\n"
    "        try:\n"
    "            result = medsam3_predictor.predict(\n"
    "                image_path=image_path, prompt=prompt,\n"
    "                threshold=SEG_THRESHOLD, nms_iou=SEG_NMS_IOU\n"
    "            )\n"
    "            if result.get('num_detections', 0) > 0:\n"
    "                # Pick detection with highest score\n"
    "                best_idx = int(np.argmax(result['scores']))\n"
    "                mask = result['masks'][best_idx].astype(bool)  # shape (H, W)\n"
    "                box  = result['boxes'][best_idx]               # xyxy\n"
    "                return mask, box\n"
    "        except Exception as e:\n"
    "            pass  # fall through to return None\n"
    "    else:\n"
    "        # SAM automatic mask: pick the largest mask (most likely the wound)\n"
    "        try:\n"
    "            masks_data = sam_mask_gen.generate(img_arr)\n"
    "            if masks_data:\n"
    "                # Filter out full-image masks (area > 80% of image)\n"
    "                masks_data = [m for m in masks_data if m['area'] < 0.8 * H * W]\n"
    "                if masks_data:\n"
    "                    best = max(masks_data, key=lambda m: m['area'])\n"
    "                    mask = best['segmentation'].astype(bool)  # (H, W)\n"
    "                    x, y, w, h = best['bbox']                 # SAM returns xywh\n"
    "                    box = [x, y, x + w, y + h]\n"
    "                    return mask, box\n"
    "        except Exception:\n"
    "            pass\n"
    "\n"
    "    return None, None\n"
    "\n"
    "\n"
    "def crop_to_wound(img_arr, bbox, padding=BBOX_PADDING):\n"
    "    \"\"\"Crop image to wound bounding box with padding.\"\"\"\n"
    "    H, W = img_arr.shape[:2]\n"
    "    x1, y1, x2, y2 = [int(v) for v in bbox]\n"
    "    x1 = max(0, x1 - padding)\n"
    "    y1 = max(0, y1 - padding)\n"
    "    x2 = min(W, x2 + padding)\n"
    "    y2 = min(H, y2 + padding)\n"
    "    # Ensure minimum crop size\n"
    "    if (x2 - x1) < 32 or (y2 - y1) < 32:\n"
    "        return img_arr  # too small, keep original\n"
    "    return img_arr[y1:y2, x1:x2]\n"
    "\n"
    "\n"
    "def copy_paste_augment(wound_arr, wound_mask, bg_arr, blur_sigma=3.0):\n"
    "    \"\"\"\n"
    "    Paste wound segment from wound_arr onto bg_arr.\n"
    "    - wound_arr : H x W x 3  numpy array\n"
    "    - wound_mask: H x W      binary numpy array (True = wound)\n"
    "    - bg_arr    : any size   numpy array (background image)\n"
    "    Returns blended image as numpy uint8 array.\n"
    "    \"\"\"\n"
    "    H, W = wound_arr.shape[:2]\n"
    "\n"
    "    # Get wound bounding box from mask\n"
    "    ys, xs = np.where(wound_mask)\n"
    "    if len(ys) == 0:\n"
    "        return wound_arr  # no mask pixels, return original\n"
    "    rmin, rmax = ys.min(), ys.max()\n"
    "    cmin, cmax = xs.min(), xs.max()\n"
    "    ph, pw = rmax - rmin + 1, cmax - cmin + 1\n"
    "\n"
    "    # Crop wound patch and its mask\n"
    "    wound_patch = wound_arr[rmin:rmax+1, cmin:cmax+1].astype(np.float32)\n"
    "    mask_patch  = wound_mask[rmin:rmax+1, cmin:cmax+1].astype(np.float32)\n"
    "\n"
    "    # Soft mask edges for natural blending\n"
    "    mask_soft = gaussian_filter(mask_patch, sigma=blur_sigma)\n"
    "    mask_soft = np.clip(mask_soft, 0.0, 1.0)\n"
    "    mask_3ch  = mask_soft[:, :, np.newaxis]  # (ph, pw, 1)\n"
    "\n"
    "    # Resize background to match wound image size\n"
    "    bg_resized = np.array(\n"
    "        Image.fromarray(bg_arr.astype(np.uint8)).resize((W, H), Image.BILINEAR),\n"
    "        dtype=np.float32\n"
    "    )\n"
    "\n"
    "    # Random paste position\n"
    "    max_y = max(0, H - ph)\n"
    "    max_x = max(0, W - pw)\n"
    "    py = random.randint(0, max_y)\n"
    "    px = random.randint(0, max_x)\n"
    "\n"
    "    # Blend wound patch over background\n"
    "    result = bg_resized.copy()\n"
    "    bg_patch = result[py:py+ph, px:px+pw]\n"
    "    if bg_patch.shape[:2] == wound_patch.shape[:2]:\n"
    "        blended = wound_patch * mask_3ch + bg_patch * (1.0 - mask_3ch)\n"
    "        result[py:py+ph, px:px+pw] = blended\n"
    "\n"
    "    return result.astype(np.uint8)\n"
    "\n"
    "\n"
    "print('Helper functions defined: segment_wound(), crop_to_wound(), copy_paste_augment()')"
))

